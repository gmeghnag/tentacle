/**
 * Export the wire protocol as one JSON Schema (2020-12) document.
 *
 * zod stays the single source of truth; this turns it into a machine-readable
 * contract for clients that cannot import `@tentacle/protocol` (Swift/Kotlin
 * codegen, external integrators), committed at `schema/protocol.json` and
 * pinned by a drift test. Run: `bun run schema:export`.
 *
 * Shape decisions (see `docs/feat/protocol-schema-export.md`):
 * - every exported `*Schema` is a named `$defs` entry; anonymous members of a
 *   discriminated union get `<Union><Tag>` names;
 * - discriminated unions are `oneOf` + OpenAPI `discriminator` (what makes a
 *   generator emit a tagged enum instead of a struct of optionals);
 * - the INPUT shape everywhere (the peer sends raw values, a receiver's
 *   validator fills `.default()`s), keeping the `default` keyword;
 * - strip (non-`.strict()`) objects stay open (`additionalProperties: true`).
 *
 * Fails loudly instead of emitting a silent hole: an unrepresentable zod kind,
 * an unlisted "anything" schema, a path `$ref`, an ambiguous or missing name.
 *
 * Build-time only: deliberately NOT re-exported from `index.ts`, so no runtime
 * consumer loads `zod-to-json-schema`.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ZodDiscriminatedUnion, ZodLiteral, ZodObject, ZodType, type ZodTypeAny, z } from "zod";
import { ignoreOverride, zodToJsonSchema } from "zod-to-json-schema";
import * as P from "./index.ts";

type Json = null | boolean | number | string | Json[] | JsonObject;
type JsonObject = { [key: string]: Json };
export type ProtocolJsonSchema = JsonObject;

/** What the exporter reads — injectable so the guards are testable with fakes. */
export interface ProtocolSource {
  exports: Record<string, unknown>;
  requestSchemas: Readonly<Record<string, { params: ZodTypeAny; result: ZodTypeAny }>>;
  notificationSchemas: Readonly<Record<string, ZodTypeAny>>;
  version: number;
  errorCodes: Readonly<Record<string, number>>;
}

export const defaultSource: ProtocolSource = {
  exports: P,
  requestSchemas: P.RequestSchemas,
  notificationSchemas: P.NotificationSchemas,
  version: P.PROTOCOL_VERSION,
  errorCodes: { ...P.JsonRpcErrorCode, ...P.DomainErrorCode },
};

/**
 * JSON pointers of the intentional "anything" (`z.unknown()`) fields. A new one
 * fails the export until it is added here — a visible, reviewed decision.
 */
export const UNKNOWN_ALLOWED: readonly string[] = [
  "#/$defs/JsonRpcError/properties/data",
  "#/$defs/JsonRpcNotification/properties/params",
  "#/$defs/JsonRpcRequest/properties/params",
  "#/$defs/JsonRpcSuccessResponse/properties/result",
  "#/$defs/ProgressParams/properties/value",
  "#/$defs/ToolCall/properties/rawInput",
  "#/$defs/WireToolDefinition/properties/parameters",
];

/** zod kinds the library maps faithfully. Anything else would be dropped or loosened silently. */
const SUPPORTED_KINDS = new Set([
  "ZodString",
  "ZodNumber",
  "ZodBoolean",
  "ZodObject",
  "ZodArray",
  "ZodDiscriminatedUnion",
  "ZodUnion",
  "ZodLiteral",
  "ZodEnum",
  "ZodOptional",
  "ZodNullable",
  "ZodDefault",
  "ZodUnknown",
  "ZodNull",
]);

/**
 * Untagged unions of objects allowed on purpose: the JSON-RPC envelopes, told
 * apart by which keys are present (`method`/`id`/`result`/`error`), never by a
 * tag. Any other one fails the export (codegen would collapse it).
 */
export const UNTAGGED_ALLOWED: readonly string[] = [
  "#/$defs/JsonRpcMessage",
  "#/$defs/JsonRpcResponse",
];

/** Members any other plain `z.union` may have (e.g. `RequestIdSchema`: string | int). */
const SCALAR_KINDS = new Set([
  "ZodString",
  "ZodNumber",
  "ZodBoolean",
  "ZodLiteral",
  "ZodEnum",
  "ZodNull",
]);

/** Keywords that only annotate: a schema made of these alone accepts anything. */
const ANNOTATION_KEYS = new Set(["description", "default", "title", "$comment"]);

const DEF_REF = /^#\/\$defs\/[A-Za-z0-9]+$/;
const SUFFIX = "Schema";

const COMMENT =
  "Generated by `bun run schema:export` from @tentacle/protocol (zod is the source of truth) — do not edit. " +
  "Shapes are the INPUT shape a receiver's validator accepts; `default` = value a receiver fills when the field is absent. " +
  "Objects with additionalProperties:true may gain optional fields without a version bump.";

function pascal(value: string): string {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter((w) => w.length > 0)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** The discriminant value of one union member, or throw. */
function tagOf(option: unknown, discriminator: string, union: string): string {
  const field = option instanceof ZodObject ? option.shape[discriminator] : undefined;
  if (!(field instanceof ZodLiteral) || typeof field.value !== "string") {
    throw new Error(`${union}: member without a string literal "${discriminator}"`);
  }
  return field.value;
}

/** Name every exported schema, then synthesize names for anonymous union members. */
function collectDefinitions(src: ProtocolSource) {
  const defs: Record<string, ZodTypeAny> = {};
  const names = new Map<ZodTypeAny, string>();
  const unions: Record<string, string> = {};
  for (const [key, value] of Object.entries(src.exports)) {
    if (!key.endsWith(SUFFIX) || !(value instanceof ZodType)) continue;
    const name = key.slice(0, -SUFFIX.length);
    const prev = names.get(value);
    if (prev !== undefined) throw new Error(`schema exported under two names: ${prev} and ${name}`);
    names.set(value, name);
    defs[name] = value;
  }
  for (const [name, schema] of Object.entries(defs)) {
    if (!(schema instanceof ZodDiscriminatedUnion)) continue;
    const discriminator: string = schema.discriminator;
    unions[name] = discriminator;
    for (const option of schema.options as ZodTypeAny[]) {
      if (names.has(option)) continue;
      const synth = name + pascal(tagOf(option, discriminator, name));
      if (defs[synth] !== undefined)
        throw new Error(`synthesized name ${synth} collides with an export`);
      names.set(option, synth);
      defs[synth] = option;
    }
  }
  return { defs, names, unions };
}

function generate(defs: Record<string, ZodTypeAny>): Record<string, JsonObject> {
  const out = zodToJsonSchema(z.object({}), {
    definitions: defs,
    definitionPath: "$defs",
    removeAdditionalStrategy: "strict",
    override: (def, refs) => {
      const kind = (def as { typeName?: string }).typeName ?? "<unknown>";
      if (!SUPPORTED_KINDS.has(kind)) {
        throw new Error(`unrepresentable zod type ${kind} at ${refs.currentPath.join("/")}`);
      }
      // A plain union of non-scalars exports as an untagged anyOf, which codegen
      // collapses into a struct of optionals: require a discriminated union.
      const options = (def as { options?: ZodTypeAny[] }).options ?? [];
      const at = refs.currentPath.join("/");
      if (
        kind === "ZodUnion" &&
        !UNTAGGED_ALLOWED.includes(at) &&
        options.some((o) => !SCALAR_KINDS.has(o._def.typeName))
      ) {
        throw new Error(`untagged union of non-scalars at ${at} — use z.discriminatedUnion`);
      }
      return ignoreOverride;
    },
  }) as unknown as JsonObject;
  const generated = out.$defs;
  if (!isObject(generated)) throw new Error("zod-to-json-schema produced no $defs");
  const result: Record<string, JsonObject> = {};
  for (const [name, schema] of Object.entries(generated)) {
    if (!isObject(schema)) throw new Error(`$defs/${name} is not a schema object`);
    result[name] = schema;
  }
  return result;
}

/** anyOf of member refs → oneOf + discriminator{propertyName, mapping}. */
function rewriteUnions(defs: Record<string, JsonObject>, unions: Record<string, string>): void {
  for (const [name, propertyName] of Object.entries(unions)) {
    const def = defs[name];
    const members = def?.anyOf;
    if (def === undefined || !Array.isArray(members)) throw new Error(`${name}: expected anyOf`);
    const mapping: JsonObject = {};
    for (const member of members) {
      const ref = isObject(member) ? member.$ref : undefined;
      if (typeof ref !== "string" || !DEF_REF.test(ref))
        throw new Error(`${name}: member is not a named $ref`);
      const target = defs[ref.slice("#/$defs/".length)];
      const properties = target?.properties;
      const tag =
        isObject(properties) && isObject(properties[propertyName])
          ? properties[propertyName].const
          : undefined;
      const required = target?.required;
      if (typeof tag !== "string" || !Array.isArray(required) || !required.includes(propertyName)) {
        throw new Error(`${name}: ${ref} lacks a required const "${propertyName}"`);
      }
      mapping[tag] = ref;
    }
    const { anyOf: _, ...rest } = def;
    defs[name] = { ...rest, oneOf: members, discriminator: { propertyName, mapping } };
  }
}

/** Walk every schema position; throw on unlisted "anything" schemas and on path refs. */
function checkHoles(defs: Record<string, JsonObject>): void {
  const holes: string[] = [];
  const badRefs: string[] = [];
  const visit = (node: Json | undefined, pointer: string): void => {
    if (!isObject(node)) return;
    if (
      Object.keys(node).every((k) => ANNOTATION_KEYS.has(k)) &&
      !UNKNOWN_ALLOWED.includes(pointer)
    ) {
      holes.push(pointer);
    }
    if (typeof node.$ref === "string" && !DEF_REF.test(node.$ref))
      badRefs.push(`${pointer} -> ${node.$ref}`);
    if (isObject(node.properties)) {
      for (const [k, child] of Object.entries(node.properties))
        visit(child, `${pointer}/properties/${k}`);
    }
    for (const key of ["anyOf", "oneOf", "allOf"]) {
      const list = node[key];
      if (Array.isArray(list)) list.forEach((child, i) => visit(child, `${pointer}/${key}/${i}`));
    }
    for (const key of ["items", "additionalProperties", "not"])
      visit(node[key], `${pointer}/${key}`);
  };
  for (const [name, schema] of Object.entries(defs)) visit(schema, `#/$defs/${name}`);
  if (badRefs.length > 0) {
    throw new Error(
      `non-name $ref (a reused anonymous schema — export it under a name): ${badRefs.join(", ")}`,
    );
  }
  if (holes.length > 0) {
    throw new Error(
      `schema accepts anything at ${holes.join(", ")} — add to UNKNOWN_ALLOWED if intended`,
    );
  }
}

/** Recursively sort object keys and `required` arrays; other arrays keep source order. */
function sortKeys(value: Json, parentKey?: string): Json {
  if (Array.isArray(value)) {
    const items = value.map((v) => sortKeys(v));
    return parentKey === "required" ? items.map(String).sort() : items;
  }
  if (isObject(value)) {
    const sorted: JsonObject = {};
    for (const key of Object.keys(value).sort()) sorted[key] = sortKeys(value[key] as Json, key);
    return sorted;
  }
  return value;
}

export function buildProtocolJsonSchema(src: ProtocolSource = defaultSource): ProtocolJsonSchema {
  const { defs, names, unions } = collectDefinitions(src);
  const generated = generate(defs);
  rewriteUnions(generated, unions);
  checkHoles(generated);
  const ref = (schema: ZodTypeAny, where: string): JsonObject => {
    const name = names.get(schema);
    if (name === undefined) throw new Error(`${where}: schema is not a named export (*Schema)`);
    return { $ref: `#/$defs/${name}` };
  };
  const methods: JsonObject = {};
  for (const [method, s] of Object.entries(src.requestSchemas)) {
    methods[method] = {
      params: ref(s.params, `${method} params`),
      result: ref(s.result, `${method} result`),
    };
  }
  const notifications: JsonObject = {};
  for (const [method, s] of Object.entries(src.notificationSchemas)) {
    notifications[method] = { params: ref(s, `${method} params`) };
  }
  const doc = sortKeys({
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $comment: COMMENT,
    title: "tentacle wire protocol",
    "x-protocol-version": src.version,
    errorCodes: { ...src.errorCodes },
    methods,
    notifications,
    $defs: generated,
  });
  if (!isObject(doc)) throw new Error("unreachable: document is not an object");
  return doc;
}

export function serializeProtocolJsonSchema(doc: ProtocolJsonSchema): string {
  return `${JSON.stringify(doc, null, 2)}\n`;
}

/** Where the committed document lives. */
export const SCHEMA_PATH = fileURLToPath(new URL("../schema/protocol.json", import.meta.url));

if (import.meta.main) {
  mkdirSync(dirname(SCHEMA_PATH), { recursive: true });
  writeFileSync(SCHEMA_PATH, serializeProtocolJsonSchema(buildProtocolJsonSchema()));
  console.log(`wrote ${SCHEMA_PATH}`);
}
